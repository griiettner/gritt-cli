test('developer namespaces allocate ticket ids independently', async () => {
  const repo = await temporaryDirectory('namespaces');
  await mkdir(path.join(repo, '.agents/tasks'), { recursive: true });
  await write(
    path.join(repo, '.agents/tasks/TKT-0001-0025/TKT-0001/task.md'),
    ticketFrontmatter('TKT-0001'),
  );

  const first = run('tkt-new.mjs', [
    '--title',
    'Alice ticket',
    '--repo-root',
    repo,
    '--namespace',
    'alice',
    '--no-sync',
  ]);
  const second = run('tkt-new.mjs', [
    '--title',
    'Bob ticket',
    '--repo-root',
    repo,
    '--namespace',
    'bob',
    '--no-sync',
  ]);
  const third = run('tkt-new.mjs', [
    '--title',
    'Alice follow-up',
    '--repo-root',
    repo,
    '--namespace',
    'alice',
    '--no-sync',
  ]);

  assert.match(first.stdout, /qualified: alice\/TKT-0001/);
  assert.match(second.stdout, /qualified: bob\/TKT-0001/);
  assert.match(third.stdout, /qualified: alice\/TKT-0002/);

  run('tkt-sync.mjs', [repo]);
  const validate = run('tkt-validate.mjs', [path.join(repo, '.agents/tasks')]);
  assert.match(validate.stdout, /tkt_validate ok/);

  const router = await readFile(
    path.join(repo, '.agents/tasks/index.yaml'),
    'utf8',
  );
  assert.match(router, /namespace: alice/);
  assert.match(router, /namespace: bob/);
  assert.match(router, /namespace: _shared/);

  const identity = await readFile(
    path.join(repo, '.agents/state/identity.local.yaml'),
    'utf8',
  );
  assert.match(identity, /github_login: alice/);
});

