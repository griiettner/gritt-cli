import assert from 'node:assert/strict';
import { access, mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

const toolsRoot = path.dirname(fileURLToPath(import.meta.url));

function run(tool, args = [], options = {}) {
  const result = spawnSync(
    process.execPath,
    [path.join(toolsRoot, tool), ...args],
    {
      cwd: options.cwd,
      env: { ...process.env, ...options.env },
      encoding: 'utf8',
    },
  );
  assert.equal(
    result.status,
    options.status ?? 0,
    `${tool} failed\nstdout:\n${result.stdout}\nstderr:\n${result.stderr}`,
  );
  return result;
}

async function temporaryDirectory(name) {
  return mkdtemp(path.join(os.tmpdir(), `gritt--`));
}

async function write(target, content) {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, content, 'utf8');
}

function ticketFrontmatter(id = 'TKT-0001') {
  return `---
id: ${id}
title: Test ticket
artifact: task
status: ready
owner: test
created: 2026-08-14
updated: 2026-08-14
dependencies: []
areas:
  - .agents/tools
skills: []
---

# Test ticket
`;
}

test('ticket indexes synchronize and validate in an isolated repository', async () => {
  const repo = await temporaryDirectory('tickets');
  await write(
    path.join(repo, '.agents/tasks/TKT-0001-0025/TKT-0001/task.md'),
    ticketFrontmatter(),
  );
  await write(
    path.join(repo, '.agents/memory/architecture/example.md'),
    `---
id: example
title: Example
tags:
  - architecture
read_when:
  - testing
---

# Example
`,
  );

  run('tkt-sync.mjs', [repo]);
  run('tkt-sync.mjs', ['--check', repo]);
  run('tkt-validate.mjs', [path.join(repo, '.agents/tasks')]);

  const router = await readFile(
    path.join(repo, '.agents/tasks/index.yaml'),
    'utf8',
  );
  const shard = await readFile(
    path.join(repo, '.agents/tasks/TKT-0001-0025/index.yaml'),
    'utf8',
  );
  assert.match(router, /namespace: _shared/);
  assert.match(router, /TKT-0001-0025/);
  assert.match(shard, /id: TKT-0001/);
  assert.match(shard, /namespace: _shared/);
});

